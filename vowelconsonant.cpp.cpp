#include<iostream>
using namespace std;
int main() {
    char A,E,I,O,U;
    cout << "Enter a Character:";
    cin >> A;
    if(A==A,E,I,O,U) {
        cout << "The Character is a Vowel= " << A << endl;
    }
    else {
        cout << "The Character is a Consonant=" << A << endl;
    } 
    return 0;
}